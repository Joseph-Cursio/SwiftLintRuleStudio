//
//  PRCommentGeneratorOptionsTests.swift
//  SwiftLintRuleStudioTests
//
//  Tests for how PRCommentOptions shape the generated comment
//

import Foundation
@testable import SwiftLintRuleStudioCore
import SwiftLintRuleStudioCoreTestSupport
import Testing

@MainActor
struct PRCommentGeneratorOptionsTests {
    // MARK: - Options Tests

    @Test("Respects includeHeader option")
    func testRespectsIncludeHeaderOption() {
        let generator = PRCommentGenerator()
        let diff = YAMLConfigurationEngine.ConfigDiff(
            addedRules: ["rule"],
            removedRules: [],
            modifiedRules: [],
            before: "",
            after: ""
        )

        let withHeader = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeHeader: true)
        )
        let withoutHeader = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeHeader: false)
        )

        #expect(withHeader.contains("## SwiftLint Configuration Changes"))
        #expect(withoutHeader.contains("## SwiftLint Configuration Changes") == false)
    }

    @Test("Respects includeFooter option")
    func testRespectsIncludeFooterOption() {
        let generator = PRCommentGenerator()
        let diff = YAMLConfigurationEngine.ConfigDiff(
            addedRules: ["rule"],
            removedRules: [],
            modifiedRules: [],
            before: "",
            after: ""
        )

        let withFooter = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeFooter: true)
        )
        let withoutFooter = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeFooter: false)
        )

        #expect(withFooter.contains("Generated by SwiftLint Rule Studio"))
        #expect(withoutFooter.contains("Generated by SwiftLint Rule Studio") == false)
    }

    @Test("Respects includeRuleLinks option")
    func testRespectsIncludeRuleLinksOption() {
        let generator = PRCommentGenerator()
        let diff = YAMLConfigurationEngine.ConfigDiff(
            addedRules: ["force_cast"],
            removedRules: [],
            modifiedRules: [],
            before: "",
            after: ""
        )

        let withLinks = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeRuleLinks: true)
        )
        let withoutLinks = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeRuleLinks: false)
        )

        #expect(withLinks.contains("](https://realm.github.io/SwiftLint/force_cast.html)"))
        #expect(withoutLinks.contains("](https://") == false)

        // The whole bullet, both ways. The two `contains` checks above pass for
        // any line carrying the URL, and so say nothing about the rest of the
        // bullet — the emoji, the backticks, the `- ` prefix. When the link
        // fragment was lifted into `ruleReference(_:linked:)` that prefix stopped
        // being written twice, and this is what pins the result.
        #expect(withLinks.contains("- [+] [`force_cast`](https://realm.github.io/SwiftLint/force_cast.html)"))
        #expect(withoutLinks.contains("- [+] `force_cast`"))
    }

    @Test("Respects includeDiffSummary option")
    func testRespectsIncludeDiffSummaryOption() {
        let generator = PRCommentGenerator()
        let diff = YAMLConfigurationEngine.ConfigDiff(
            addedRules: ["rule"],
            removedRules: [],
            modifiedRules: [],
            before: "",
            after: ""
        )

        let withSummary = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeDiffSummary: true)
        )
        let withoutSummary = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(includeDiffSummary: false)
        )

        #expect(withSummary.contains("### Summary"))
        #expect(withoutSummary.contains("### Summary") == false)
    }

    @Test("Respects customTitle option")
    func testRespectsCustomTitleOption() {
        let generator = PRCommentGenerator()
        let diff = YAMLConfigurationEngine.ConfigDiff(
            addedRules: ["rule"],
            removedRules: [],
            modifiedRules: [],
            before: "",
            after: ""
        )
        let markdown = generator.generateMarkdown(
            from: diff,
            options: PRCommentOptions(customTitle: "Custom Title Here")
        )

        #expect(markdown.contains("## Custom Title Here"))
        #expect(markdown.contains("## SwiftLint Configuration Changes") == false)
    }

    @Test("Minimal options produce compact output")
    func testMinimalOptionsProduceCompactOutput() {
        let generator = PRCommentGenerator()
        let diff = YAMLConfigurationEngine.ConfigDiff(
            addedRules: ["rule"],
            removedRules: [],
            modifiedRules: [],
            before: "",
            after: ""
        )
        let markdown = generator.generateMarkdown(from: diff, options: .minimal)

        #expect(markdown.contains("## SwiftLint") == false)
        #expect(markdown.contains("### Summary") == false)
        #expect(markdown.contains("Generated by") == false)
        #expect(markdown.contains("](https://") == false)
        #expect(markdown.contains("`rule`"))
    }
}
